use crate::mb::MbRequiresEntry;

pub(in crate::scene) struct RenderedDocument {
    pub text: String,
    pub issues: Vec<EmissionIssue>,
}

pub(in crate::scene) fn render_best_effort_maya_ascii(
    metadata: &RecoveredHeader,
    scene_model: &SceneModel,
    source_path: &Path,
    output_name: &str,
    node_angular_attrs: &HashMap<String, HashMap<String, AngularAttrKind>>,
    embed_metadata: bool,
) -> RenderedDocument {
    let mut context = EmitContext::default();
    context.set_target("header", output_name);
    let time_render_context = build_time_render_context(metadata);
    let angular_render_unit = build_angular_render_unit(metadata);

    let vers = metadata.maya_version();

    let mut lines = vec![
        format!("//Maya ASCII {} scene", escape_ma_comment(vers)),
        format!("//Name: {}", escape_ma_comment(output_name)),
    ];
    if embed_metadata {
        lines.push(format!(
            "//Source: {}",
            escape_ma_comment(&source_path.to_string_lossy())
        ));
    }
    lines.push("//Generated by maya-scene-kit best-effort converter.".to_string());
    lines.push("//WARNING: This file may be incomplete or invalid for Maya load.".to_string());

    if let Some(chng) = &metadata.chng {
        lines.push(format!("//Source CHNG: {}", escape_ma_comment(chng)));
    }

    lines.push(String::new());
    let maya_requires = render_maya_requires(vers, &mut context);
    lines.push(maya_requires.clone());

    let mut seen = HashSet::new();
    seen.insert(maya_requires);
    for req in &metadata.requires {
        let mut requires_context = EmitContext::default();
        let rendered = render_requires_entry(req, &mut requires_context);
        if seen.insert(rendered.clone()) {
            context.issues.extend(requires_context.issues);
            lines.push(rendered);
        }
    }

    if !scene_model.reference_files.is_empty() {
        // FREF recovery preserves encounter order from the MB sections, but Maya ASCII writes
        // scene-level reference commands in a different normalized order: all `file -rdi`
        // records first in reference-tree preorder, then the top-level `file -r -dr 1` lines.
        lines.extend(render_reference_file_ops(
            &scene_model.reference_files,
            &mut context,
        ));
    }

    context.set_target("header", output_name);
    let mut units = Vec::new();
    for (flag, value, position) in [
        ("-l", metadata.linear_unit(), "currentUnit.linear"),
        ("-a", metadata.angular_unit(), "currentUnit.angular"),
        ("-t", metadata.time_unit(), "currentUnit.time"),
    ] {
        if let Some(value) =
            render_ma_bare_word(value, BareWordPosition::Unit, &mut context, position)
        {
            units.push(format!("{flag} {value}"));
        }
    }
    if !units.is_empty() {
        lines.push(format!("currentUnit {};", units.join(" ")));
    }

    for (key, value) in &metadata.file_info {
        lines.push(format!(
            "fileInfo \"{}\" \"{}\";",
            escape_ma_string(key, &mut context, "fileInfo.key"),
            escape_ma_string(value, &mut context, "fileInfo.value")
        ));
    }
    lines.push(String::new());

    lines.push("//Recovered nodes/attributes from .mb chunks (best effort).".to_string());

    for node in &scene_model.nodes {
        context.set_target(&node.node_type, &node.name);
        let node_type = render_ma_bare_word(
            &node.node_type,
            BareWordPosition::NodeType,
            &mut context,
            "createNode.node_type",
        )
        .expect("node types support quoted literals");
        let set_attr_render_context = SetAttrRenderContext {
            time_render_context: time_render_context.as_ref(),
            angular_render_unit,
            angular_attrs: node_angular_attrs.get(&node.name),
        };
        let shared_part = if node.create_flags.shared.is_true() {
            " -s"
        } else {
            ""
        };
        let skip_select_part = if node.create_flags.skip_select.is_true() {
            " -ss"
        } else {
            ""
        };
        let parent_part = node
            .parent
            .as_ref()
            .map(|parent| {
                format!(
                    " -p \"{}\"",
                    escape_ma_string(parent, &mut context, "createNode.parent")
                )
            })
            .unwrap_or_default();
        lines.push(format!(
            "createNode {}{}{} -n \"{}\"{};",
            node_type,
            shared_part,
            skip_select_part,
            escape_ma_string(&node.name, &mut context, "createNode.name"),
            parent_part
        ));
        if let Some(uid) = &node.uid {
            lines.push(format!(
                "\trename -uid \"{}\";",
                escape_ma_string(uid, &mut context, "rename.uid")
            ));
        }
        for attr in &node.attrs {
            match attr {
                RecoveredAttrOp::AddAttr(op) => {
                    if let Some(add_attr) = render_add_attr_op(op, &mut context) {
                        lines.push(format!("\t{add_attr}"));
                    }
                }
                RecoveredAttrOp::SetAttr(op) => lines.push(format!(
                    "\t{}",
                    render_set_attr_op_with_render_context(
                        op,
                        set_attr_render_context,
                        &mut context
                    )
                )),
                RecoveredAttrOp::RefEdit { attr_name, data } => {
                    let cmd = format_reference_edits_setattr_from_data(
                        &attr_path(attr_name),
                        data,
                        &mut context,
                    );
                    // Quoted values contain no raw CR or LF, so only formatting splits here.
                    for line in cmd.lines() {
                        lines.push(format!("\t{line}"));
                    }
                }
            }
        }
        for note in &node.decode_notes {
            lines.push(format!(
                "\t//decode-note: {}",
                escape_ma_comment(&note.to_decode_note())
            ));
        }
        if node.node_type.as_ref() == "script" && distinct_script_bodies(node).len() > 1 {
            lines.push(
                "\t//decode-note: inferred attr=.b reason=multiple divergent script bodies recovered for this script node".to_string(),
            );
        }
        lines.push(String::new());
    }

    if scene_model.nodes.is_empty() {
        lines.push("//No node stubs recovered.".to_string());
    }

    lines.push("//Recovered select blocks from SLCT chunks (best effort).".to_string());
    if scene_model.select_blocks.is_empty() {
        lines.push("//No SLCT blocks recovered.".to_string());
    } else {
        for block in &scene_model.select_blocks {
            lines.extend(render_select_block(
                block,
                time_render_context.as_ref(),
                angular_render_unit,
                node_angular_attrs,
                &mut context,
            ));
        }
    }
    lines.push(String::new());

    lines.push("//Recovered links from CONS chunks (best effort).".to_string());
    if scene_model.links.is_empty() {
        lines.push("//No links recovered.".to_string());
    } else {
        lines.extend(
            scene_model
                .links
                .iter()
                .map(|link| render_link_op(link, &mut context)),
        );
    }
    lines.push(String::new());

    lines.push("//End of best-effort conversion output.".to_string());
    RenderedDocument {
        text: lines.join("\n") + "\n",
        issues: context.issues,
    }
}

fn render_maya_requires(version: &str, context: &mut EmitContext) -> String {
    format!(
        "requires maya \"{}\";",
        escape_ma_string(version, context, "requires.version")
    )
}

fn render_requires_entry(entry: &MbRequiresEntry, context: &mut EmitContext) -> String {
    context.set_target("requires", &entry.plugin_name);
    let mut options_part = String::new();
    if let Some(options) = &entry.options {
        let words: Vec<_> = options.split_whitespace().collect();
        let is_flag = |word: &str| {
            word.strip_prefix('-').is_some_and(|name| {
                !name.is_empty() && name.bytes().all(|b| b.is_ascii_alphabetic())
            })
        };
        if words.len() % 2 != 0
            || words
                .chunks_exact(2)
                .any(|pair| !is_flag(pair[0]) || is_flag(pair[1]))
        {
            let reason = format!(
                "omitted requires plugin={} version={}: malformed options",
                entry.plugin_name, entry.version
            );
            context.record("requires.options", options, &reason);
            return format!("//{}", escape_ma_comment(&reason));
        }
        let mut cursor = 0;
        options_part.push(' ');
        for pair in words.chunks_exact(2) {
            let value = pair[1];
            let start = value.as_ptr() as usize - options.as_ptr() as usize;
            options_part.push_str(&options[cursor..start]);
            options_part.push_str(
                &render_ma_bare_word(
                    value,
                    BareWordPosition::RequiresValue,
                    context,
                    "requires.options",
                )
                .expect("requires values support quoted literals"),
            );
            cursor = start + value.len();
        }
        options_part.push_str(&options[cursor..]);
    }
    format!(
        "requires{} \"{}\" \"{}\";",
        options_part,
        escape_ma_string(&entry.plugin_name, context, "requires.plugin_name"),
        escape_ma_string(&entry.version, context, "requires.version")
    )
}

fn attr_path(attr_name: &str) -> String {
    if attr_name.starts_with('.') {
        attr_name.to_string()
    } else {
        format!(".{attr_name}")
    }
}

fn distinct_script_bodies(node: &RecoveredNode) -> Vec<&str> {
    let mut bodies = Vec::new();
    for attr in &node.attrs {
        let RecoveredAttrOp::SetAttr(op) = attr else {
            continue;
        };
        if op.attr_name_or_path != ".b" {
            continue;
        }
        let SetAttrValue::String(body) = &op.value else {
            continue;
        };
        if !bodies.iter().any(|existing| existing == &body.as_str()) {
            bodies.push(body.as_str());
        }
    }
    bodies
}
